#ifndef UTIL_PAGESIZE_H_
#define UTIL_PAGESIZE_H_

#ifdef _WIN32
#include <windows.h>
#else
#include <unistd.h>
#endif

static size_t get_page_size() {
#ifdef _WIN32
    SYSTEM_INFO si;
    GetSystemInfo(&si);
    return (size_t)si.dwPageSize;
#else
    long size = sysconf(_SC_PAGESIZE);
    return (size > 0) ? (size_t)size : 0;
#endif
}

#endif // UTIL_PAGESIZE_H_
